#!/usr/bin/env python3
"""Write the Wokwi scenarios (spec 8.2) for the siren_node_sim and gauge_v3_sim images.

    python firmware/tools/gen_wokwi.py           # rewrite firmware/wokwi/*/scenarios/*.yaml
    python firmware/tools/gen_wokwi.py --check   # exit 1 if a checked-in scenario is stale (CI)

The signed commands and LoRa frames come from the backend's canonical codec
(backend/src/Pukaar/services/devices/protocol.py, loaded by path: it needs only the standard library),
with TEST ONLY keys derived from the public test root (bytes 0x00..0x1f), the same root the simulator
images compile in (lib/pukaar_common/pkr_test_keys.h). Nothing here is a secret, and nothing signed
here means anything to a real device. The output is deterministic: a fixed clock, fixed ids.

The scenario steps (wait-serial, write-serial, delay, expect-pin, set-control) are the Wokwi CLI's
automation format. They run in CI only when a WOKWI_CLI_TOKEN secret exists (.github/workflows/
firmware.yml); they have not been run here.
"""
from __future__ import annotations

import argparse
import base64
import importlib.util
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
REPO = ROOT.parent
WOKWI = ROOT / "wokwi"
TEST_ONLY_ROOT = bytes(range(32))
T0 = 1761121800  # 2025-10-22T08:30:00Z = 14:00 IST: inside the 09:00-18:00 audible-test window
SIREN, GAUGE, BOX = "siren-thunag-sim", "gauge-janjehli-sim", "box-thunag-sim"
ADDR = {SIREN: 0x0101, BOX: 0x0102, GAUGE: 0x0201}
# backend services/devices/siren_model.PATTERN_DEFAULTS (the device plays what the signed command says)
DEFAULTS = {"W1": (5, 900, 2, 1200, 100), "C1": (10, 600, 3, 2700, 100)}


def protocol():
    path = REPO / "backend" / "src" / "Pukaar" / "services" / "devices" / "protocol.py"
    spec = importlib.util.spec_from_file_location("pukaar_protocol", path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["pukaar_protocol"] = mod  # dataclasses look the module up while it loads
    spec.loader.exec_module(mod)
    return mod


P = protocol()


def key(device: str) -> bytes:
    return P.derive_device_key(TEST_ONLY_ROOT, device, 1)


def cmd(cid: str, pattern: str, ctr: int, *, iat: int = T0, exp: int | None = None, tamper: bool = False) -> str:
    cycles, every, rcycles, cap, vol = DEFAULTS[pattern]
    c = {"id": cid, "action": "sound", "pattern": pattern, "clip": "thunag.warning.hi.v1" if pattern == "W1" else "thunag.critical.hi.v1",
         "clip_sha256_16": None, "level": "warning" if pattern == "W1" else "critical",
         "alert_id": "alr_wokwi_test_only", "cycles": cycles, "repeat_every_s": every, "repeat_cycles": rcycles,
         "cap_on_s": cap, "volume": vol, "iat": iat, "exp": exp if exp is not None else iat + 1800, "ctr": ctr,
         "src": "approval", "kid": 1}
    c["sig"] = P.sign_command(key(SIREN), c, SIREN)
    if tamper:
        c["sig"] = ("A" if c["sig"][0] != "A" else "B") + c["sig"][1:]
    return ">CMD " + json.dumps(c, separators=(",", ":"))


def gauge_alarm(ctr: int, ts: int, stage: int = 312) -> str:
    payload = P.pack_payload(P.FrameType.GAUGE_ALARM, {"level": 3, "stage_cm": stage, "rise_10min_cm": 41, "quality": 95,
                                                       "cloud_ok": 0, "rain_15min_tenths_mm": 87})
    frame = P.encode_frame(key(GAUGE), ftype=P.FrameType.GAUGE_ALARM, src=ADDR[GAUGE], dst=P.BROADCAST, ctr=ctr, ts=ts,
                           payload=payload)
    return ">LORA " + base64.b64encode(frame).decode()


def q(s: str) -> str:
    """A YAML double-quoted scalar (the line ends in a newline: the firmware reads whole lines)."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '\\n"'


def w(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def scenario(name: str, title: str, steps: list[str]) -> str:
    head = ["# GENERATED by firmware/tools/gen_wokwi.py: TEST ONLY keys. Do not edit by hand.",
            f"name: {w(title)}", "version: 1", "author: Pukaar", "", "steps:"]
    return "\n".join(head + [f"  - {s}" for s in steps]) + "\n"


def write(line: str) -> str:
    return "write-serial: " + q(line)


AUTONOMY_CFG = ('>CFG {"autonomy":{"enabled":true,"shadow_mode":false,"fast_path":false,'
                f'"upstream":["{GAUGE}"]}}}}')
SHADOW_CFG = ('>CFG {"autonomy":{"enabled":true,"shadow_mode":true,"fast_path":false,'
              f'"upstream":["{GAUGE}"]}}}}')


def siren_scenarios() -> dict[str, str]:
    start = ["wait-serial: 'READY'", write(f">TIME {T0}")]
    k1_on = "expect-pin: { part-id: k1, pin: IN, value: 1 }"
    k1_off = "expect-pin: { part-id: k1, pin: IN, value: 0 }"
    return {
        "warning_signed": scenario("warning_signed", "A signed Warning sounds and verifies", start + [
            write(cmd("cmd_wokwi_w1", "W1", 101)), "wait-serial: '\"type\":\"started\"'", "delay: 500ms", k1_on,
            "wait-serial: '\"type\":\"verified\"'"]),
        "bad_sig": scenario("bad_sig", "A bad signature is refused and the relays stay off", start + [
            write(cmd("cmd_wokwi_bad", "W1", 102, tamper=True)), "wait-serial: '\"reason\":\"bad_sig\"'", "delay: 500ms",
            k1_off]),
        "replay": scenario("replay", "The same command again is refused as replayed", start + [
            write(cmd("cmd_wokwi_replay", "W1", 103)), "wait-serial: '\"type\":\"started\"'",
            write(cmd("cmd_wokwi_replay", "W1", 103)), "wait-serial: '\"reason\":\"replayed\"'"]),
        "expired": scenario("expired", "An expired command is refused", start + [
            write(cmd("cmd_wokwi_old", "W1", 104, iat=T0 - 3600, exp=T0 - 1800)),
            "wait-serial: '\"reason\":\"expired\"'", "delay: 500ms", k1_off]),
        "critical_preempts": scenario("critical_preempts", "Critical pre-empts Warning", start + [
            write(cmd("cmd_wokwi_w", "W1", 105)), "wait-serial: '\"type\":\"started\"'",
            write(cmd("cmd_wokwi_c", "C1", 106)), "wait-serial: '\"type\":\"stopped\"'",
            "wait-serial: '\"cmd_id\":\"cmd_wokwi_c\",\"pattern\":\"C1\"'"]),
        "manual_hold": scenario("manual_hold", "Key at C and HOLD for 3 s sounds MANUAL with an audit event", start + [
            write(">KEY c"), write(">HOLD 1"), "wait-serial: '\"type\":\"manual_trigger\"'", write(">HOLD 0"),
            "delay: 500ms", k1_on]),
        "short_hold": scenario("short_hold", "A 2 s hold does nothing", start + [
            write(">KEY c"), write(">HOLD 1"), "delay: 2000ms", write(">HOLD 0"), "delay: 2000ms", k1_off]),
        "autonomy": scenario("autonomy", "No cloud and a signed GAUGE_ALARM from upstream: AUTONOMOUS", start + [
            write(AUTONOMY_CFG), write(">CLOUD down"), write(gauge_alarm(1, T0 + 2)),
            "wait-serial: '\"type\":\"autonomous_trigger\"'", "wait-serial: '<SMS'", "delay: 500ms", k1_on]),
        "shadow_mode": scenario("shadow_mode", "Shadow mode logs what it would have done and stays silent", start + [
            write(SHADOW_CFG), write(">CLOUD down"), write(gauge_alarm(1, T0 + 2)),
            "wait-serial: '\"would_sound\":true'", "delay: 500ms", k1_off]),
        "silent_test_fault": scenario("silent_test_fault", "The silent test fails on an amplifier fault", start + [
            write(">FAULT amp_open"), write(">TEST silent"), "wait-serial: '\"kind\":\"silent\",\"ok\":false'"]),
    }


def gauge_scenarios() -> dict[str, str]:
    start = ["wait-serial: 'READY'", write(f">TIME {T0}")]
    return {
        "critical_alarm": scenario("critical_alarm", "2 of 3 readings at Critical send GAUGE_ALARM on LoRa", start + [
            write(">STAGE 120"), write(">WAKE"), "wait-serial: 'alarm=0'",
            write(">STAGE 310"), write(">WAKE"), "wait-serial: 'alarm=0'",
            write(">STAGE 315"), write(">WAKE"), "wait-serial: 'level=3 alarm=1'", "wait-serial: '<LORA '"]),
        "blind_zone": scenario("blind_zone", "A blocked sensor face is never a flood", start + [
            write(">STAGE 120"), write(">WAKE"), "wait-serial: 'alarm=0'",
            write(">BLIND"), write(">WAKE"), "wait-serial: 'alarm=0'",
            write(">WAKE"), "wait-serial: 'alarm=0'", write(">WAKE"), "wait-serial: 'level=0 alarm=0'"]),
        "rain_burst": scenario("rain_burst", "Two bucket tips in a minute wake the CPU and set the burst cadence", start + [
            write(">STAGE 120"),
            "set-control: { part-id: bucket, control: pressed, value: 1 }", "delay: 120ms",
            "set-control: { part-id: bucket, control: pressed, value: 0 }", "delay: 800ms",
            "set-control: { part-id: bucket, control: pressed, value: 1 }",
            "wait-serial: '<RAINWAKE'",  # 25 ms into the second press: wait before releasing it
            "delay: 100ms", "set-control: { part-id: bucket, control: pressed, value: 0 }",
            write(">WAKE"), "wait-serial: 'sleep=60'"]),
    }


def outputs() -> dict[pathlib.Path, str]:
    out = {}
    for name, text in siren_scenarios().items():
        out[WOKWI / "siren_node" / "scenarios" / f"{name}.yaml"] = text
    for name, text in gauge_scenarios().items():
        out[WOKWI / "gauge_v3" / "scenarios" / f"{name}.yaml"] = text
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(REPO)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    if stale:
        print("stale Wokwi scenarios (python firmware/tools/gen_wokwi.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    print("Wokwi scenarios " + ("current" if args.check else "written") + f": {len(outputs())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

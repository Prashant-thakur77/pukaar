#!/usr/bin/env python3
"""Generate firmware/lib/pukaar_common/schema.h from firmware/schema/devices.yaml.

    python firmware/tools/gen_schema.py           # rewrite the header
    python firmware/tools/gen_schema.py --check   # exit 1 if the checked-in header is stale (CI)

Needs PyYAML. The output is deterministic (no timestamps) so --check is a plain byte compare.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "schema" / "devices.yaml"
OUT = ROOT / "lib" / "pukaar_common" / "schema.h"


def ident(s: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in str(s)).upper()


def enum(lines: list[str], prefix: str, items: dict, comment: str) -> None:
    lines.append(f"/* {comment} */")
    lines.append("enum {")
    for name, val in items.items():
        v = val["id"] if isinstance(val, dict) else val
        lines.append(f"  PKR_{prefix}_{ident(name)} = {v},")
    lines.append("};")


def name_table(lines: list[str], fn: str, items: dict) -> None:
    """A switch from id to the wire name, and a lookup from name to id (-1 if unknown)."""
    pairs = [((v["id"] if isinstance(v, dict) else v), k) for k, v in items.items()]
    lines.append(f"static inline const char *pkr_{fn}_name(int id) {{")
    lines.append("  switch (id) {")
    for v, k in pairs:
        lines.append(f'    case {v}: return "{k}";')
    lines.append('    default: return "?";')
    lines.append("  }")
    lines.append("}")
    lines.append(f"static inline int pkr_{fn}_from_name(const char *s) {{")
    lines.append("  if (!s) return -1;")
    for v, k in pairs:
        lines.append(f'  if (pkr__streq(s, "{k}")) return {v};')
    lines.append("  return -1;")
    lines.append("}")


def render(doc: dict) -> str:
    L: list[str] = []
    L.append("/* GENERATED by firmware/tools/gen_schema.py from firmware/schema/devices.yaml. DO NOT EDIT.")
    L.append(" * Change the YAML and re-run the generator; CI fails when this file is stale. */")
    L.append("#ifndef PUKAAR_SCHEMA_H")
    L.append("#define PUKAAR_SCHEMA_H")
    L.append("")
    L.append(f"#define PKR_SCHEMA_VERSION {doc['version']}")
    L.append(f'#define PKR_PROTOCOL "{doc["protocol"]}"')
    L.append("")
    L.append("static inline int pkr__streq(const char *a, const char *b) {")
    L.append("  while (*a && *a == *b) { a++; b++; }")
    L.append("  return *a == *b;")
    L.append("}")
    L.append("")

    for key, prefix, comment, fn in [
        ("levels", "LEVEL", "alert levels", "level"),
        ("cmd_levels", "CMDLEVEL", "command levels (0 = none)", "cmd_level"),
        ("actions", "ACTION", "command actions", "action"),
        ("patterns", "PATTERN", "alarm patterns (section 4.1)", "pattern"),
        ("sources", "SRC", "trigger sources", "src"),
        ("vias", "VIA", "command paths", "via"),
        ("priorities", "PRIO", "priority ranks, higher wins", None),
        ("states", "STATE", "reported states", "state"),
        ("events", "EVT", "event types", "event"),
        ("reasons", "REASON", "rejection reasons", "reason"),
        ("buttons", "BUTTON", "buttons", "button"),
        ("key_positions", "KEY", "key switch positions", None),
        ("power_tiers", "TIER", "power tiers (section 3.1)", None),
    ]:
        enum(L, prefix, doc[key], comment)
        if fn:
            name_table(L, fn, doc[key])
        L.append("")

    L.append("/* SMS letters (section 5.4) */")
    for name, v in doc["actions"].items():
        L.append(f"#define PKR_SMS_ACTION_{ident(name)} '{v['sms']}'")
    for name, v in doc["patterns"].items():
        if v.get("sms"):
            L.append(f"#define PKR_SMS_PATTERN_{ident(name)} '{v['sms']}'")
    L.append("")
    L.append("/* pattern -> the command level it carries */")
    L.append("static inline int pkr_pattern_cmd_level(int pattern) {")
    L.append("  switch (pattern) {")
    for name, v in doc["patterns"].items():
        if v.get("level"):
            L.append(f"    case {v['id']}: return PKR_CMDLEVEL_{ident(v['level'])};")
    L.append("    default: return -1;")
    L.append("  }")
    L.append("}")
    L.append("")

    for name, v in doc["power_tiers"].items():
        L.append(f"#define PKR_TIER_{ident(name)}_MIN_SOC {v['min_soc']}")
    L.append("")

    L.append("/* events that go to the outbox alarm queue (never dropped, sent first) */")
    L.append("static inline int pkr_event_is_alarm(int evt) {")
    L.append("  switch (evt) {")
    for name in doc["alarm_queue_events"]:
        L.append(f"    case PKR_EVT_{ident(name)}:")
    L.append("      return 1;")
    L.append("    default: return 0;")
    L.append("  }")
    L.append("}")
    L.append("")

    for key, prefix in [("gauge_err_bits", "ERR"), ("rain_err_bits", "RAIN_ERR")]:
        for name, v in doc[key].items():
            L.append(f"#define PKR_{prefix}_{ident(name)} {v}u")
        L.append("")

    fr = doc["frame"]
    L.append("/* LoRa frame (section 5.3) */")
    for k in ("version", "header_len", "mac_len", "max_payload", "max_len", "ts_window_s"):
        L.append(f"#define PKR_FRAME_{ident(k)} {fr[k]}")
    L.append(f"#define PKR_FRAME_BROADCAST 0x{fr['broadcast']:04X}u")
    L.append("enum {")
    for name, t in fr["types"].items():
        L.append(f"  PKR_FT_{name} = 0x{t['id']:02X},")
    L.append("};")
    for name, t in fr["types"].items():
        L.append(f"#define PKR_FT_{name}_LEN {t['len']}  /* {t['layout']} */")
    L.append("static inline int pkr_frame_payload_len(int type) {")
    L.append("  switch (type) {")
    for name, t in fr["types"].items():
        L.append(f"    case 0x{t['id']:02X}: return {t['len']};")
    L.append("    default: return -1;")
    L.append("  }")
    L.append("}")
    L.append("static inline const char *pkr_frame_role(int type) {")
    L.append("  switch (type) {")
    for name, t in fr["types"].items():
        L.append(f'    case 0x{t["id"]:02X}: return "{t["role"]}";')
    L.append("    default: return 0;")
    L.append("  }")
    L.append("}")
    L.append("")

    sh = doc["shadow"]
    L.append("/* named shadow `siren` desired.cmd: canonical signing order (section 5.1) */")
    L.append(f"#define PKR_CMD_FIELD_COUNT {len(sh['cmd_fields'])}")
    L.append("static const char *const PKR_CMD_FIELDS[PKR_CMD_FIELD_COUNT] = {")
    L.append("  " + ", ".join(f'"{f}"' for f in sh["cmd_fields"]))
    L.append("};")
    L.append(f"#define PKR_CMD_SIG_BYTES {sh['sig_bytes']}")
    L.append("")

    sms = doc["sms"]
    for k, v in sms.items():
        L.append(f"#define PKR_SMS_{ident(k)} {v}")
    L.append("")

    L.append("/* MQTT topics (section 5.1) */")
    for k, v in doc["topics"].items():
        L.append(f'#define PKR_TOPIC_{ident(k)} "{v}"')
    L.append("")

    for group, prefix in [("limits", "LIMIT"), ("outbox", "OUTBOX"), ("dutycycle", "DUTY"),
                          ("radio", "RADIO"), ("rain", "RAIN")]:
        L.append(f"/* {group} */")
        for k, v in doc[group].items():
            val = f"0x{v:X}u" if k in ("record_magic", "sync_word") else f"{v}"
            if isinstance(v, int) and v > 0x7FFFFFFF:
                val += "u"
            L.append(f"#define PKR_{prefix}_{ident(k)} {val}")
        L.append("")

    L.append("#endif /* PUKAAR_SCHEMA_H */")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the header is stale")
    args = ap.parse_args()
    text = render(yaml.safe_load(SRC.read_text(encoding="utf-8")))
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT.parent)} is stale: run python firmware/tools/gen_schema.py", file=sys.stderr)
            return 1
        print("schema.h is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

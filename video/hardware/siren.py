"""Siren sounds for the hardware explainer, synthesised from scratch (no samples, no third-party audio).

usage: python3 siren.py out_dir
Writes 48 kHz stereo float wavs that follow the alarm patterns in docs/hardware/ALARM.md, shortened for the film:
  siren_w1.wav  "तीन लंबी" (Warning): steady 650 Hz tones, as the Beas dam-release hooter convention (one 3 s tone here)
  siren_c1.wav  "लहर" (Critical): a rising and falling 500-1,050 Hz wail (8 s here; the real pattern runs 60 s)
A horn-like timbre (odd harmonics, soft clipping), heard from across a valley (low-pass, a simple echo and reverb).
Same output every run. Original work generated by this script, dedicated to the public domain under CC0 1.0.
"""
import os
import sys

import numpy as np
import soundfile as sf
from scipy.signal import butter, sosfilt

SR = 48000
OUT = sys.argv[1]
os.makedirs(OUT, exist_ok=True)


def horn(freq):
    """A horn tone following an instantaneous frequency curve (Hz per sample)."""
    ph = 2 * np.pi * np.cumsum(freq) / SR
    y = np.sin(ph) + 0.45 * np.sin(3 * ph) + 0.22 * np.sin(5 * ph) + 0.1 * np.sin(7 * ph)
    return np.tanh(1.6 * y) / np.tanh(1.6)


def distance(y, seed):
    """Across the valley: a gentle low-pass, two echoes off the hillsides and a short diffuse tail."""
    y = sosfilt(butter(2, 3200, btype="low", fs=SR, output="sos"), y)
    out = np.concatenate([y, np.zeros(int(2.5 * SR))])
    for d, g in ((0.42, 0.32), (0.91, 0.18)):
        k = int(d * SR)
        out[k:k + len(y)] += g * y
    rng = np.random.default_rng(seed)
    ir = rng.standard_normal(int(1.2 * SR)) * np.exp(-np.linspace(0, 7, int(1.2 * SR)))
    ir = sosfilt(butter(2, 2500, btype="low", fs=SR, output="sos"), ir) * 0.012
    wet = np.convolve(out, ir)[: len(out)]
    L = out + wet
    R = np.roll(out, 90) + np.roll(wet, 400)
    return L, R


def write(name, L, R):
    y = np.stack([L, R], axis=1)
    y = y / (np.abs(y).max() + 1e-9) * 0.85
    f = int(0.03 * SR)
    y[:f] *= np.linspace(0, 1, f)[:, None]
    y[-f:] *= np.linspace(1, 0, f)[:, None]
    sf.write(os.path.join(OUT, f"{name}.wav"), y.astype(np.float32), SR, subtype="FLOAT")


# W1: one steady 650 Hz tone, 3 s, with a soft attack and release
n = int(3.0 * SR)
env = np.minimum(1, np.minimum(np.arange(n) / (0.12 * SR), (n - np.arange(n)) / (0.25 * SR)))
write("siren_w1", *distance(horn(np.full(n, 650.0)) * env, 3))

# C1: rising and falling between 500 and 1,050 Hz, one sweep up and down every 4 s
n = int(8.0 * SR)
t = np.arange(n) / SR
f = 500 + 550 * (0.5 - 0.5 * np.cos(2 * np.pi * t / 4.0))
env = np.minimum(1, np.minimum(t / 0.4, (8.0 - t) / 0.8))
write("siren_c1", *distance(horn(f) * env, 5))
print(f"siren sounds in {OUT}")

"""An original score for the pitch video, synthesised from scratch (no samples, no third-party audio).

usage: python3 score.py cues.json out.wav
cues.json: {"duration": s, "sections": [{"from": s, "to": s, "mood": m, "gain_db": 0}], "hits": [s, ...],
            "drops": [[s, dur], ...]}
Moods, in the video's order: night (a low drone and a slow heartbeat), sombre (piano over a D-minor pad), tense
(pulsing low strings and a ticking clock), hope (the pad opens into D major, rising piano), drive (100 bpm: kick,
clap, hats, bass, pluck arpeggio, pad), build (drive with a fuller arpeggio), reflect (drums out, piano and pad),
resolve (a last D-major swell that rings out). Sections cross-fade over 1.6 s. "hits" are low impacts on reveals;
"drops" pull the score out for a moment of silence before a reveal. Original work generated by this script,
dedicated to the public domain under CC0 1.0. Loudness is set in mix.py.
"""
import json
import sys

import numpy as np
import soundfile as sf
from scipy.signal import butter, oaconvolve, sosfilt

SR = 48000
cues = json.load(open(sys.argv[1]))
OUT = sys.argv[2]
DUR = float(cues["duration"]) + 3.0
N = int(DUR * SR)
rng = np.random.default_rng(5)


def hz(m):
    return 440.0 * 2 ** ((m - 69) / 12)


def lp(x, f, o=2):
    return sosfilt(butter(o, f, btype="low", fs=SR, output="sos"), x)


def hp(x, f, o=2):
    return sosfilt(butter(o, f, btype="high", fs=SR, output="sos"), x)


class Bus:
    def __init__(self):
        self.L = np.zeros(N)
        self.R = np.zeros(N)

    def add(self, sig, t0, pan=0.5, gain=1.0):
        a = int(t0 * SR)
        if a >= N or a + len(sig) <= 0:
            return
        s = sig
        if a < 0:
            s, a = s[-a:], 0
        b = min(N, a + len(s))
        s = s[: b - a] * gain
        self.L[a:b] += s * np.cos(pan * np.pi / 2)
        self.R[a:b] += s * np.sin(pan * np.pi / 2)


# ---------------------------------------------------------------- instruments
def pad(notes, d, bright=0.5, att=1.6, rel=2.4):
    n = int((d + rel) * SR)
    t = np.arange(n) / SR
    y = np.zeros(n)
    for m in notes:
        f0 = hz(m)
        for k in range(1, 7):
            amp = (1 / k) * np.exp(-k / (1.4 + 3 * bright))
            for dc in (-7, 0, 7):
                f = f0 * k * 2 ** (dc / 1200)
                if f < 6000:
                    y += amp * np.sin(2 * np.pi * f * t + rng.uniform(0, 6.28))
    e = np.minimum(1, t / att) * np.where(t > d, np.exp(-(t - d) / (rel / 3)), 1)
    return lp(y * e, 900 + 2600 * bright) / (len(notes) * 3)


def piano(m, vel=0.6, d=3.5):
    n = int(d * SR)
    t = np.arange(n) / SR
    f0 = hz(m)
    y = np.zeros(n)
    B = 0.0004
    for k in range(1, 10):
        f = f0 * k * np.sqrt(1 + B * k * k)
        if f > 9000:
            break
        y += (0.9 ** k) / k ** 0.7 * np.sin(2 * np.pi * f * t) * np.exp(-t * (0.9 + 0.55 * k))
    hammer = hp(rng.standard_normal(n), 2000) * np.exp(-t / 0.004) * 0.05
    y = (y + hammer) * (1 - np.exp(-t / 0.002))
    return y * vel * 0.35


def pluck(m, vel=0.5, d=0.9):
    n = int(d * SR)
    t = np.arange(n) / SR
    f = hz(m)
    y = (np.sin(2 * np.pi * f * t) + 0.35 * np.sin(4 * np.pi * f * t) + 0.12 * np.sin(6 * np.pi * f * t))
    return y * np.exp(-t / 0.22) * (1 - np.exp(-t / 0.003)) * vel * 0.22


def bass(m, d=0.42, vel=0.8):
    n = int((d + 0.08) * SR)
    t = np.arange(n) / SR
    f = hz(m)
    y = np.sin(2 * np.pi * f * t) + 0.3 * np.sin(4 * np.pi * f * t) + 0.1 * np.sign(np.sin(2 * np.pi * f * t))
    e = (1 - np.exp(-t / 0.004)) * np.where(t < d, 1, np.exp(-(t - d) / 0.03))
    return lp(y * e, 700) * vel * 0.4


def kick(vel=1.0):
    n = int(0.45 * SR)
    t = np.arange(n) / SR
    return np.sin(2 * np.pi * (50 + 110 * np.exp(-t * 35)) * t) * np.exp(-t / 0.16) * vel * 0.9


def clap(vel=0.6):
    n = int(0.3 * SR)
    t = np.arange(n) / SR
    noise = rng.standard_normal(n)
    e = sum(np.exp(-np.maximum(0, t - d) / 0.012) * (t >= d) for d in (0, 0.011, 0.022)) + np.exp(-t / 0.09) * 0.6
    y = sosfilt(butter(2, [900, 5000], btype="band", fs=SR, output="sos"), noise) * e
    return y * vel * 0.3


def hat(vel=0.3, open_=False):
    n = int((0.25 if open_ else 0.06) * SR)
    t = np.arange(n) / SR
    return hp(rng.standard_normal(n), 7000) * np.exp(-t / (0.08 if open_ else 0.015)) * vel * 0.25


def string_pulse(m, d=0.25, vel=0.5):
    n = int((d + 0.1) * SR)
    t = np.arange(n) / SR
    f = hz(m)
    saw = 2 * ((f * t) % 1) - 1
    e = np.minimum(1, t / 0.015) * np.where(t < d, 1, np.exp(-(t - d) / 0.04))
    return lp(saw * e, 1200) * vel * 0.15


def tick():
    n = int(0.05 * SR)
    t = np.arange(n) / SR
    return hp(rng.standard_normal(n), 4000) * np.exp(-t / 0.004) * 0.12


def impact():
    n = int(2.5 * SR)
    t = np.arange(n) / SR
    y = np.sin(2 * np.pi * (42 + 60 * np.exp(-t * 14)) * t) * np.exp(-t / 0.7)
    y += lp(rng.standard_normal(n), 220) * np.exp(-t / 0.25) * 0.5
    return y * 0.8


# ---------------------------------------------------------------- moods (each writes into its own bus, a..b seconds)
Dm = [[38, 50, 53, 57, 62], [34, 46, 50, 53, 58], [41, 48, 53, 57, 60], [36, 48, 52, 55, 60]]  # Dm Bb F C
DM = [[38, 50, 54, 57, 62, 66], [33, 45, 52, 57, 61, 64], [35, 47, 50, 54, 59, 62], [31, 43, 50, 55, 59, 62]]  # D A Bm G


def mood_night(bus, a, b):
    d = b - a
    bus.add(pad([26, 38, 45], d, bright=0.15, att=3.0), a, 0.5, 1.4)
    t = a + 0.8
    while t < b - 0.5:  # a slow heartbeat on the sub
        for off, v in ((0, 1.0), (0.28, 0.6)):
            n = int(0.35 * SR)
            tt = np.arange(n) / SR
            bus.add(np.sin(2 * np.pi * 46 * tt) * np.exp(-tt / 0.12) * v * 0.6, t + off)
        t += 1.75
    n = int(d * SR)  # a thin, high shimmer
    tt = np.arange(n) / SR
    sh = np.sin(2 * np.pi * hz(81) * tt) * (0.5 + 0.5 * np.sin(2 * np.pi * tt / 5)) * 0.015
    bus.add(sh * np.minimum(1, tt / 3), a, 0.7)


def mood_sombre(bus, a, b, bpm=72):
    beat = 60 / bpm
    bar = beat * 4
    i, t = 0, a
    motif = [62, 65, 69, 67, 65, 64, 62, 57]
    while t < b:
        ch = Dm[i % 4]
        dur = min(bar * 2, b - t + 1.5)
        bus.add(pad(ch, dur, bright=0.3), t, 0.5, 1.1)
        for k in range(4):
            m = motif[(i * 4 + k) % len(motif)]
            if t + k * beat * 2 < b:
                bus.add(piano(m, 0.5 + 0.15 * (k == 0)), t + k * beat * 2, 0.4 + 0.1 * k)
        bus.add(piano(ch[0] + 12, 0.45, 5), t, 0.3)
        t += bar * 2
        i += 1


def mood_tense(bus, a, b, bpm=96):
    beat = 60 / bpm
    i, t = 0, a
    prog = [[38, 50, 53, 57], [38, 50, 53, 58], [34, 46, 50, 53], [36, 48, 52, 55]]
    while t < b:
        ch = prog[i % 4]
        bus.add(pad(ch[1:], beat * 4 + 0.5, bright=0.2), t, 0.5, 0.8)
        for k in range(8):
            tt = t + k * beat / 2
            if tt < b:
                bus.add(string_pulse(ch[0] + 12, beat / 2 * 0.7, 0.6 if k % 2 == 0 else 0.4), tt, 0.45)
                bus.add(string_pulse(ch[2] + 12, beat / 2 * 0.7, 0.35), tt, 0.6)
        for k in range(4):
            if t + k * beat < b:
                bus.add(tick(), t + k * beat, 0.7)
        t += beat * 4
        i += 1


def mood_hope(bus, a, b, bpm=80):
    beat = 60 / bpm
    bar = beat * 4
    i, t = 0, a
    while t < b:
        ch = DM[i % 4]
        bright = min(0.85, 0.35 + 0.12 * i)
        bus.add(pad(ch, bar + 0.4, bright=bright), t, 0.5, 1.0)
        arp = [ch[1] + 12, ch[2] + 12, ch[3] + 12, ch[4] + 12, ch[5] + 12, ch[4] + 12]
        for k in range(8):
            tt = t + k * beat / 2
            if tt < b:
                bus.add(piano(arp[k % len(arp)], 0.32 + 0.04 * min(i, 4)), tt, 0.3 + 0.05 * k)
        bus.add(piano(ch[0] + 12, 0.5, 4), t, 0.35)
        t += bar
        i += 1


def mood_drive(bus, a, b, bpm=100, full=False):
    beat = 60 / bpm
    bar = beat * 4
    i, t = 0, a
    while t < b:
        ch = DM[i % 4]
        bus.add(pad(ch[1:], bar + 0.3, bright=0.6, att=0.4, rel=0.8), t, 0.5, 0.55)
        for k in range(4):
            tb = t + k * beat
            if tb >= b:
                break
            if k in (0, 2):
                bus.add(kick(1.0 if k == 0 else 0.85), tb, 0.5)
            if k in (1, 3):
                bus.add(clap(0.55), tb, 0.52)
            for h in range(2):
                bus.add(hat(0.32 if h else 0.2), tb + h * beat / 2, 0.62)
            # bass: root on 1, a push on the and-of-2, the fifth on 4
            if k == 0:
                bus.add(bass(ch[0] + 12, beat * 0.9), tb, 0.5)
            if k == 1:
                bus.add(bass(ch[0] + 12, beat * 0.4, 0.6), tb + beat / 2, 0.5)
            if k == 3:
                bus.add(bass(ch[0] + 19, beat * 0.45, 0.7), tb, 0.5)
        arp = [ch[2] + 12, ch[3] + 12, ch[4] + 12, ch[5] + 12]
        steps = 16 if full else 8
        for k in range(steps):
            tt = t + k * bar / steps
            if tt < b and (full or rng.random() < 0.8):
                bus.add(pluck(arp[(k * 3) % 4] + (12 if full and k % 4 == 3 else 0), 0.5), tt, 0.25 + 0.5 * ((k * 7) % 4) / 4)
        t += bar
        i += 1


def mood_reflect(bus, a, b, bpm=80):
    beat = 60 / bpm
    bar = beat * 4
    i, t = 0, a
    prog = [DM[3], DM[0], DM[1], DM[2]]  # G D A Bm
    while t < b:
        ch = prog[i % 4]
        bus.add(pad(ch, bar + 0.5, bright=0.55), t, 0.5, 1.0)
        for k, m in enumerate([ch[2] + 12, ch[3] + 12, ch[4] + 12, ch[3] + 12]):
            if t + k * beat < b:
                bus.add(piano(m, 0.38), t + k * beat, 0.35 + 0.1 * k)
        if t < b:
            bus.add(kick(0.45), t, 0.5)
        t += bar
        i += 1


def mood_resolve(bus, a, b):
    d = b - a
    seq = [DM[3], DM[1], DM[0]]  # G, A ... D
    k = max(1.6, (d - 4) / 3)
    for i, ch in enumerate(seq):
        last = i == len(seq) - 1
        dd = d - k * i if last else k + 0.6
        bus.add(pad(ch, dd, bright=0.7, att=0.8, rel=4), a + k * i, 0.5, 1.2)
        for j, m in enumerate(ch[2:]):
            bus.add(piano(m + 12, 0.45, 6 if last else 3.5), a + k * i + j * 0.18, 0.3 + 0.12 * j)
        bus.add(piano(ch[0] + 12, 0.55, 7 if last else 3.5), a + k * i, 0.5)


MOODS = {"night": mood_night, "sombre": mood_sombre, "tense": mood_tense, "hope": mood_hope,
         "drive": mood_drive, "build": lambda bus, a, b: mood_drive(bus, a, b, full=True),
         "reflect": mood_reflect, "resolve": mood_resolve}

XF = 1.6
mixL, mixR = np.zeros(N), np.zeros(N)
for s in cues["sections"]:
    bus = Bus()
    a, b = float(s["from"]), float(s["to"])
    MOODS[s["mood"]](bus, a, b + XF)
    g = np.zeros(N)
    ia, ib = int(a * SR), int(min(DUR, b + XF) * SR)
    g[ia:ib] = 1
    fi = int(min(XF, b - a) * SR)
    if a > 0:
        g[ia:ia + fi] = np.linspace(0, 1, fi)
    g[max(ia, ib - int(XF * SR)):ib] *= np.linspace(1, 0, ib - max(ia, ib - int(XF * SR)))
    gain = 10 ** (s.get("gain_db", 0) / 20)
    mixL += bus.L * g * gain
    mixR += bus.R * g * gain

hits = Bus()
for t in cues.get("hits", []):
    hits.add(impact(), float(t), 0.5, 1.0)
mixL += hits.L
mixR += hits.R

# drops: a short silence before a reveal (fast fade down, quick return)
gain = np.ones(N)
for t, d in cues.get("drops", []):
    a, b = int(float(t) * SR), int((float(t) + float(d)) * SR)
    f = int(0.25 * SR)
    gain[max(0, a - f):a] *= np.linspace(1, 0.05, min(f, a))
    gain[a:b] *= 0.05
    gain[b:b + f] *= np.linspace(0.05, 1, len(gain[b:b + f]))
mixL *= gain
mixR *= gain

# a shared hall reverb
irn = int(2.8 * SR)
ti = np.arange(irn) / SR
irL = lp(rng.standard_normal(irn) * np.exp(-ti / 0.75), 4000)
irR = lp(rng.standard_normal(irn) * np.exp(-ti / 0.75), 4000)
irL /= np.sqrt((irL ** 2).sum())
irR /= np.sqrt((irR ** 2).sum())
wetL = oaconvolve(mixL, irL)[:N]
wetR = oaconvolve(mixR, irR)[:N]
L = hp(0.7 * mixL + 0.32 * wetL, 30)
R = hp(0.7 * mixR + 0.32 * wetR, 30)
y = np.stack([L, R], axis=1)
y /= np.abs(y).max() + 1e-9
y *= 0.6
sf.write(OUT, y.astype(np.float32), SR, subtype="FLOAT")
print(f"score: {DUR:.1f} s, {len(cues['sections'])} sections -> {OUT}")

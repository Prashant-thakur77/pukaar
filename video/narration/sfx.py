"""Sound effects for the pitch video, synthesised from scratch (no samples, no third-party audio).

usage: python3 sfx.py out_dir
Writes 48 kHz stereo float wavs: rain (a 60 s bed), thunder_a/_b, river (a 30 s bed), paper_slam, paper_slide, whoosh,
riser, hit, chime (a neutral two-note notification, not any app's sound), tick, tap, clock, bell, swell. Same output
every run (fixed seeds). Original work generated by this script, dedicated to the public domain under CC0 1.0.
"""
import os
import sys

import numpy as np
import soundfile as sf
from scipy.signal import butter, sosfilt, sosfiltfilt

SR = 48000
OUT = sys.argv[1]
os.makedirs(OUT, exist_ok=True)


def rng(seed):
    return np.random.default_rng(seed)


def bp(x, lo, hi, order=2):
    return sosfilt(butter(order, [lo, hi], btype="band", fs=SR, output="sos"), x)


def lp(x, f, order=2):
    return sosfilt(butter(order, f, btype="low", fs=SR, output="sos"), x)


def hp(x, f, order=2):
    return sosfilt(butter(order, f, btype="high", fs=SR, output="sos"), x)


def pink(n, r):
    # Voss-McCartney-ish: filtered white noise with a -3 dB/octave tilt
    w = r.standard_normal(n)
    b = [0.049922035, -0.095993537, 0.050612699, -0.004408786]
    a = [1, -2.494956002, 2.017265875, -0.522189400]
    from scipy.signal import lfilter
    return lfilter(b, a, w)


def brown(n, r):
    x = np.cumsum(r.standard_normal(n))
    x = hp(x, 20)
    return x / (np.abs(x).max() + 1e-9)


def env_ad(n, a, d, curve=3.0):
    t = np.arange(n) / SR
    e = np.minimum(1, t / max(a, 1e-4)) * np.exp(-np.maximum(0, t - a) * curve / max(d, 1e-4))
    return e


def write(name, L, R=None, peak=0.9):
    R = L if R is None else R
    y = np.stack([L, R], axis=1)
    y = y / (np.abs(y).max() + 1e-9) * peak
    sf.write(os.path.join(OUT, f"{name}.wav"), y.astype(np.float32), SR, subtype="FLOAT")


def stereo_decorrelate(x, r, ms=11):
    d = int(ms / 1000 * SR)
    return x, np.concatenate([np.zeros(d), x[:-d]]) * 0.9 + x * 0.1


# ---------------------------------------------------------------- rain: a steady hiss, drops and a low wash
def rain():
    r = rng(1)
    n = SR * 60
    hiss = bp(pink(n, r), 600, 9000) * 0.55
    wash = lp(brown(n, r), 400) * 0.35
    drops = np.zeros(n)
    for _ in range(9000):
        a = r.integers(0, n - 400)
        k = r.integers(40, 260)
        drops[a:a + k] += r.uniform(0.2, 1.0) * np.exp(-np.arange(k) / (k / 5)) * r.choice([-1, 1])
    drops = bp(drops, 1500, 7000) * 0.4
    mod = 0.85 + 0.15 * np.sin(2 * np.pi * np.arange(n) / SR / 9.0)
    x = (hiss + wash + drops) * mod
    L = x
    R = np.roll(bp(pink(n, rng(2)), 600, 9000) * 0.55 + wash + np.roll(drops, 3333), 0) * mod
    # loop-friendly ends
    f = SR
    L[:f] *= np.linspace(0, 1, f); R[:f] *= np.linspace(0, 1, f)
    L[-f:] *= np.linspace(1, 0, f); R[-f:] *= np.linspace(1, 0, f)
    write("rain", L, R, peak=0.7)


# ---------------------------------------------------------------- thunder: a crack, then rolling rumble
def thunder(name, seed, crack=0.8, length=7.0):
    r = rng(seed)
    n = int(SR * length)
    t = np.arange(n) / SR
    rumble = lp(brown(n, r), 160, 4) * 2.5
    swells = np.zeros(n)
    for c, amp, w in [(0.15, 1.0, 0.5), (0.9, 0.8, 0.9), (1.9, 0.6, 1.2), (3.2, 0.4, 1.5)]:
        c += r.uniform(-0.1, 0.2)
        swells += amp * np.exp(-((t - c) / w) ** 2) * (t > c - w)
    swells += 0.25 * np.exp(-t / 2.5)
    x = rumble * swells
    ck = hp(r.standard_normal(n), 1200) * np.exp(-t / 0.08) * (t < 0.6) * crack
    ck2 = bp(r.standard_normal(n), 300, 3000) * np.exp(-np.maximum(0, t - 0.05) / 0.35) * (t > 0.05) * crack * 0.6
    y = x + ck + ck2
    y[-SR:] *= np.linspace(1, 0, SR)
    L, R = y, np.roll(y, 240) * 0.95
    write(name, L, R, peak=0.95)


# ---------------------------------------------------------------- river: a heavy low roar with movement
def river():
    r = rng(3)
    n = SR * 30
    t = np.arange(n) / SR
    roar = bp(brown(n, r), 80, 900) * 1.2 + bp(pink(n, r), 300, 3000) * 0.35
    gurgle = bp(r.standard_normal(n), 200, 1200) * (0.5 + 0.5 * np.sin(2 * np.pi * t * 0.7 + np.sin(2 * np.pi * t * 0.13) * 3))
    x = roar + 0.25 * gurgle
    x *= 0.9 + 0.1 * np.sin(2 * np.pi * t / 6.1)
    L = x
    R = bp(brown(n, rng(4)), 80, 900) * 1.2 + bp(pink(n, rng(5)), 300, 3000) * 0.35 + 0.25 * np.roll(gurgle, 5000)
    f = SR
    for c in (L, R):
        c[:f] *= np.linspace(0, 1, f); c[-f:] *= np.linspace(1, 0, f)
    write("river", L, R, peak=0.7)


# ---------------------------------------------------------------- paper: a slam (cut lands) and a slide
def paper_slam():
    r = rng(6)
    n = int(SR * 0.9)
    t = np.arange(n) / SR
    air = bp(r.standard_normal(n), 800, 6000) * np.exp(-((t - 0.07) / 0.05) ** 2)
    thump = np.sin(2 * np.pi * (70 + 60 * np.exp(-t * 40)) * t) * np.exp(-t / 0.09) * (t > 0.1)
    rustle = np.zeros(n)
    for _ in range(140):
        a = int(r.uniform(0.1, 0.45) * SR)
        k = r.integers(30, 160)
        rustle[a:a + k] += r.uniform(0.2, 1) * r.standard_normal(k) * np.exp(-np.arange(k) / 40)
    rustle = bp(rustle, 2000, 9000) * np.exp(-np.maximum(0, t - 0.1) / 0.15)
    snap = hp(r.standard_normal(n), 2500) * np.exp(-np.maximum(0, t - 0.1) / 0.012) * (t > 0.1)
    y = 0.5 * air + 1.2 * thump + 0.45 * rustle + 0.6 * snap
    write("paper_slam", y, np.roll(y, 120), peak=0.9)


def paper_slide():
    r = rng(7)
    n = int(SR * 0.7)
    t = np.arange(n) / SR
    e = np.sin(np.pi * np.clip(t / 0.6, 0, 1)) ** 2
    x = bp(r.standard_normal(n), 1500, 7000) * e
    crk = np.zeros(n)
    for _ in range(90):
        a = r.integers(0, n - 200)
        crk[a:a + 60] += r.standard_normal(60) * np.exp(-np.arange(60) / 15)
    y = x * 0.6 + hp(crk, 3000) * e * 0.5
    write("paper_slide", y, np.roll(y, 300), peak=0.8)


# ---------------------------------------------------------------- whoosh: pink noise through a swept band-pass
def whoosh(name="whoosh", d=0.8, seed=8):
    r = rng(seed)
    n = int(SR * d)
    t = np.arange(n) / SR
    x = pink(n, r)
    out = np.zeros(n)
    hop = 512
    for i in range(0, n, hop):
        p = i / n
        f = 300 * (12 ** np.sin(np.pi * p))
        seg = x[max(0, i - 2048): i + hop]
        y = sosfilt(butter(2, [max(80, f * 0.6), min(16000, f * 1.6)], btype="band", fs=SR, output="sos"), seg)
        out[i:i + hop] = y[-min(hop, n - i):]
    e = np.sin(np.pi * t / d) ** 2
    y = out * e
    L = y * np.linspace(1.2, 0.6, n)
    R = y * np.linspace(0.6, 1.2, n)
    write(name, L, R, peak=0.85)


# ---------------------------------------------------------------- riser: a chirp plus rising filtered noise
def riser(d=2.2):
    r = rng(9)
    n = int(SR * d)
    t = np.arange(n) / SR
    chirp = np.sin(2 * np.pi * (180 * t + 260 * t * t / d))
    noise = hp(pink(n, r), 1500)
    e = (t / d) ** 2.6
    y = 0.4 * chirp * e + 0.7 * noise * e
    y[-int(0.03 * SR):] *= np.linspace(1, 0, int(0.03 * SR))
    write("riser", y, np.roll(y, 200), peak=0.8)


def hit():
    n = int(SR * 2.2)
    t = np.arange(n) / SR
    boom = np.sin(2 * np.pi * (48 + 70 * np.exp(-t * 18)) * t) * np.exp(-t / 0.55)
    body = lp(rng(10).standard_normal(n), 300) * np.exp(-t / 0.12) * 0.8
    y = boom + body
    write("hit", y, y, peak=0.95)


def chime():
    # a neutral two-note notification (A5 then E6), soft bell partials; not any app's sound
    n = int(SR * 1.6)
    t = np.arange(n) / SR
    y = np.zeros(n)
    for t0, f in [(0.0, 880.0), (0.14, 1318.5)]:
        tt = np.maximum(0, t - t0)
        on = t >= t0
        for k, a in [(1, 1), (2.76, 0.25), (5.4, 0.08)]:
            y += on * a * np.sin(2 * np.pi * f * k * tt) * np.exp(-tt / (0.5 / k ** 0.5))
    write("chime", y, y, peak=0.7)


def tick():
    n = int(SR * 0.06)
    t = np.arange(n) / SR
    y = np.sin(2 * np.pi * 2300 * t) * np.exp(-t / 0.006) + 0.4 * hp(rng(11).standard_normal(n), 4000) * np.exp(-t / 0.003)
    write("tick", y, y, peak=0.6)


def tap():
    n = int(SR * 0.12)
    t = np.arange(n) / SR
    y = np.sin(2 * np.pi * (300 + 600 * np.exp(-t * 80)) * t) * np.exp(-t / 0.02) + 0.3 * bp(rng(12).standard_normal(n), 1000, 5000) * np.exp(-t / 0.008)
    write("tap", y, y, peak=0.7)


def clock():
    # a dry mechanical tick
    n = int(SR * 0.1)
    t = np.arange(n) / SR
    y = bp(rng(13).standard_normal(n), 2500, 7000) * np.exp(-t / 0.004) + 0.5 * np.sin(2 * np.pi * 1800 * t) * np.exp(-t / 0.01)
    write("clock", y, y, peak=0.6)


def bell():
    # a small hand bell rung three times, soft and distant
    n = int(SR * 3.2)
    t = np.arange(n) / SR
    y = np.zeros(n)
    for t0 in (0.0, 0.32, 0.64, 0.96):
        tt = np.maximum(0, t - t0)
        on = t >= t0
        for k, a in [(1, 1), (2.32, 0.5), (4.25, 0.3), (6.8, 0.12)]:
            y += on * a * np.sin(2 * np.pi * 1180 * k * tt + t0) * np.exp(-tt / (0.9 / k))
    y = lp(y, 6000)
    write("bell", y, np.roll(y, 400), peak=0.6)


def swell():
    # a soft reversed-cymbal swell for reveals
    r = rng(14)
    n = int(SR * 1.6)
    t = np.arange(n) / SR
    x = hp(pink(n, r), 3000) * (t / 1.6) ** 3
    write("swell", x, np.roll(x, 500), peak=0.7)


rain(); thunder("thunder_a", 21, 1.0, 7.5); thunder("thunder_b", 22, 0.5, 6.0); river()
paper_slam(); paper_slide(); whoosh(); whoosh("whoosh_short", 0.45, 15); riser(); hit(); chime(); tick(); tap(); clock()
bell(); swell()
print(f"sfx written to {OUT}")
